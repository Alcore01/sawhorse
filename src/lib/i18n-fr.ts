/** "2 solids, the outline of a face" in French. */
function frWhat(s: string): string {
  return s
    .replace(/\bthe outlines of (\d+) faces\b/g, "les contours de $1 faces")
    .replace(/\bthe outline of a face\b/g, "le contour d'une face")
    .replace(/\b(\d+) solids?\b/g, (_, n) => `${n} volume${n === "1" ? "" : "s"}`)
    .replace(/\b(\d+) groups?\b/g, (_, n) => `${n} groupe${n === "1" ? "" : "s"}`)
    .replace(/\b(\d+) edges?\b/g, (_, n) => `${n} arête${n === "1" ? "" : "s"}`);
}

/** The reasons the kernel gives for a refused point or merge (E-41, E-50, E-54). */
function frWhy(s: string): string {
  const known: Record<string, string> = {
    "it joins three edges or more (only a point between two edges can go)": "trois arêtes ou plus s'y rejoignent (seul un point entre deux arêtes peut partir)",
    "it is a corner where three edges or more meet (only a point between two edges can go)": "c'est un coin où se rejoignent trois arêtes ou plus (seul un point entre deux arêtes peut partir)",
    "it is a point of a curve (Explode Curve first)": "c'est un point d'une courbe (Éclater la courbe d'abord)",
    "it ends an edge (erase the edge instead)": "il termine une arête (effacez l'arête)",
    "there is no point of this sketch there": "il n'y a pas de point de cette esquisse ici",
    "there is no point of this solid there": "il n'y a pas de point de ce volume ici",
    "a face would be left with two corners": "une face n'aurait plus que deux coins",
    "select two faces of one solid or more": "sélectionnez au moins deux faces d'un volume",
    "a face with a hole": "une face trouée",
    "they do not touch along an edge": "elles ne se touchent pas par une arête",
    "their corners fit no plane": "leurs coins ne tiennent dans aucun plan",
    "its two edges are not in line (it is more than 5 cm off the line), or the straight edge would touch other lines":
      "ses deux arêtes ne sont pas alignées (à plus de 5 cm de la ligne), ou l'arête droite toucherait d'autres lignes",
  };
  if (known[s]) return known[s];
  return s
    .replace(/^its two edges are not in line \((\d+) cm off the line, at most (\d+) cm\)$/, "ses deux arêtes ne sont pas alignées ($1 cm de la ligne, au plus $2 cm)")
    .replace(/^they are (\d+) cm out of one plane \(at most (\d+) cm\)$/, "elles sont à $1 cm d'un même plan (au plus $2 cm)")
    .replace(/^removing it would bend a face beside it.*$/, "le retirer tordrait une face voisine");
}

